export function getActiveLanguage() {
  try {
    const localeCfg = JSON.parse(localStorage.getItem('graceos_locale_config') || '{}');
    if (localeCfg.language) return localeCfg.language.split('-')[0].toLowerCase();
    
    const advCfg = JSON.parse(localStorage.getItem('app_advanced_config') || '{}');
    const raw = advCfg.language || advCfg.defaultLanguage || 'ta';
    return raw.split('-')[0].toLowerCase();
  } catch {
    return 'ta';
  }
}

export function t(key) {
  const lang = getActiveLanguage();
  return TRANSLATIONS[lang]?.[key] || TRANSLATIONS['en']?.[key] || key;
}